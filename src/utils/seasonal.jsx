export const getGreetingByTime = (d = new Date()) => {
	const hour = d.getHours();
	if (hour < 11) {
		return {
			title: "Selamat Pagi",
			subtitle: "Semangat belajar hari ini!",
			image: "/kebersamaan.jpg"
		};
	} else if (hour < 15) {
		return {
			title: "Selamat Siang",
			subtitle: "Tetap produktif!",
			image: "/kebersamaan.jpg"
		};
	} else if (hour < 18) {
		return {
			title: "Selamat Sore",
			subtitle: "Sudah hampir selesai hari ini!",
			image: "/kebersamaan.jpg"
		};
	} else {
		return {
			title: "Selamat Malam", 
			subtitle: "Istirahat yang nyenyak.",
			image: "/kebersamaan.jpg"
		};
	}
};
